using System.Text;

namespace oopshell.Scanner;

/// <summary>Resolves interface and enum names, local or from referenced protocol assemblies.</summary>
public sealed class TypeResolver(string localNamespace, IReadOnlyList<Protocol> local, IReadOnlyDictionary<string, string> externalNamespaces)
{
    readonly HashSet<string> localNames = new(local.SelectMany(p => p.Interfaces).SelectMany(i =>
        new[] { i.Name }.Concat(i.Enums.Select(e => i.Name + "." + e.Name))));

    public string LocalNamespace => localNamespace;

    public List<string> Missing { get; } = new();

    public bool IsLocal(string name) => localNames.Contains(name);

    /// <summary>The C# type for an interface, or null (and a recorded miss) if unknown.</summary>
    public string? InterfaceType(string name) => TypeFor(name, Names.Pascal(name));

    /// <summary>The C# type for an enum reference like <c>wl_output.transform</c>, or null if unknown.</summary>
    public string? EnumType(string owningInterface, string reference)
    {
        string qualified = reference.Contains('.') ? reference : owningInterface + "." + reference;
        int dot = qualified.IndexOf('.');
        return TypeFor(qualified, Names.Pascal(qualified.Substring(0, dot)) + Names.Pascal(qualified.Substring(dot + 1)));
    }

    string? TypeFor(string protocolName, string csharpName)
    {
        if (localNames.Contains(protocolName))
            return csharpName;
        if (externalNamespaces.TryGetValue(protocolName, out var ns))
            return $"global::{ns}.{csharpName}";
        if (!Missing.Contains(protocolName))
            Missing.Add(protocolName);
        return null;
    }
}

/// <summary>Emits C# for parsed protocols. Output is deterministic: it depends only on the inputs.</summary>
public sealed class Emitter(TypeResolver types)
{
    static readonly string[] ReservedMembers =
    {
        "Handle", "BoundVersion", "Id", "Class", "Dispose", "IsDisposed", "Equals", "GetHashCode", "ToString",
        "GetType", "Destroy", "Dispatch", "Marshal", "MarshalNew", "Wrap", "InterfaceName", "MaxVersion", "NativeInterface",
    };

    const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591, CS1573\nusing System;\nusing oopshell.Native;\nusing oopshell.Protocol;\n\n";

    /// <summary>The source for one protocol: proxy classes, event structs and enums.</summary>
    public string EmitProtocol(Protocol protocol)
    {
        var w = new CodeWriter();
        w.Raw(Header);
        w.Line($"namespace {types.LocalNamespace};");
        foreach (var iface in protocol.Interfaces)
        {
            w.Line();
            EmitInterface(w, iface);
            foreach (var e in iface.Events.Where(e => e.Args.Count > 0))
            {
                w.Line();
                EmitEventStruct(w, iface, e);
            }
            foreach (var def in iface.Enums)
            {
                w.Line();
                EmitEnum(w, iface, def);
            }
        }
        return w.ToString();
    }

    /// <summary>The source for the native <c>wl_interface</c> tables of all local interfaces.</summary>
    public string EmitTables(IReadOnlyList<Protocol> protocols)
    {
        var all = protocols.SelectMany(p => p.Interfaces).ToList();
        var w = new CodeWriter();
        w.Raw(Header);
        string names = string.Join(" ", all.Select(i => i.Name).Concat(all.SelectMany(i => i.Enums.Select(e => i.Name + "." + e.Name))));
        w.Line($"[assembly: WaylandProtocols(\"{types.LocalNamespace}\", \"{names}\")]");
        w.Line();
        w.Line($"namespace {types.LocalNamespace};");
        w.Line();
        w.Line("/// <summary>Native <c>wl_interface</c> tables, built once on first use.</summary>");
        w.Open("internal static unsafe class WaylandInterfaces");
        foreach (var iface in all)
            w.Line($"public static readonly WlInterface* {iface.Name} = WlInterfaceTable.Allocate();");
        w.Line();
        w.Open("static WaylandInterfaces()");
        foreach (var iface in all)
        {
            w.Line($"WlInterfaceTable.Fill({iface.Name}, \"{iface.Name}\", {iface.Version},");
            w.Indent++;
            w.Line(MessageArray(iface.Requests) + ",");
            var errors = iface.Enums.FirstOrDefault(e => e.Name == "error");
            if (errors is null)
                w.Line(MessageArray(iface.Events) + ");");
            else
            {
                w.Line(MessageArray(iface.Events) + ",");
                w.Line("[" + string.Join(", ", errors.Entries.Select(e => $"({e.Value}, \"{e.Name}\")")) + "]);");
            }
            w.Indent--;
        }
        w.Close();
        w.Close();
        return w.ToString();
    }

    string MessageArray(List<Message> messages)
    {
        if (messages.Count == 0)
            return "[]";
        return "[" + string.Join(", ", messages.Select(m =>
            $"WlInterfaceTable.Message(\"{m.Name}\", \"{Signature(m)}\"{TypeList(m)})")) + "]";
    }

    static string Signature(Message message)
    {
        var sb = new StringBuilder();
        if (message.Since > 1)
            sb.Append(message.Since);
        foreach (var arg in message.Args)
        {
            if (arg.AllowNull)
                sb.Append('?');
            sb.Append(arg.Type switch
            {
                ArgType.Int => "i",
                ArgType.Uint => "u",
                ArgType.Fixed => "f",
                ArgType.String => "s",
                ArgType.Object => "o",
                ArgType.NewId => arg.Interface is null ? "sun" : "n",
                ArgType.Array => "a",
                _ => "h",
            });
        }
        return sb.ToString();
    }

    // Messages without object args omit the list; the native types array is then all nulls.
    string TypeList(Message message) =>
        message.Args.Any(a => a.Type is ArgType.Object or ArgType.NewId && a.Interface is not null)
            ? string.Concat(TypeTable(message).Select(t => ", " + t))
            : "";

    IEnumerable<string> TypeTable(Message message)
    {
        foreach (var arg in message.Args)
        {
            if (arg.Type == ArgType.NewId && arg.Interface is null)
            {
                yield return "null";
                yield return "null";
                yield return "null";
            }
            else if (arg.Type is ArgType.Object or ArgType.NewId && arg.Interface is not null)
            {
                yield return types.IsLocal(arg.Interface) ? arg.Interface : (types.InterfaceType(arg.Interface) is { } t ? t + ".NativeInterface" : "null");
            }
            else
            {
                yield return "null";
            }
        }
    }

    void EmitInterface(CodeWriter w, Interface iface)
    {
        string cls = Names.Pascal(iface.Name);
        var dispose = DisposeDestructor(iface);
        var eventNames = MemberNames(iface);

        Docs(w, iface.Description);
        w.Open($"public sealed unsafe partial class {cls} : WlProxy, IWaylandProxy<{cls}>");
        w.Line($"public static string InterfaceName => \"{iface.Name}\";");
        w.Line($"public static uint MaxVersion => {iface.Version};");
        w.Line($"public static WlInterface* NativeInterface => WaylandInterfaces.{iface.Name};");
        w.Line($"public static {cls} Wrap(nint handle) => new(handle);");
        w.Line();
        w.Line(iface.Name == "wl_display"
            ? $"private {cls}(nint handle) : base(handle, dispatch: false) {{ }}"
            : $"private {cls}(nint handle) : base(handle) {{ }}");

        for (int opcode = 0; opcode < iface.Requests.Count; opcode++)
        {
            var request = iface.Requests[opcode];
            w.Line();
            if (request == dispose)
                EmitDisposeDestructor(w, request, opcode);
            else
                EmitRequest(w, iface, request, opcode);
        }

        foreach (var e in iface.Events)
        {
            w.Line();
            Docs(w, e.Description, e.Since);
            string handler = e.Args.Count == 0 ? "Action" : $"Action<{EventStructName(iface, e)}>";
            w.Line($"public event {handler}? {eventNames[e]};");
        }

        if (iface.Events.Count > 0)
        {
            w.Line();
            w.Open("protected override void Dispatch(uint opcode, WlArgument* args)");
            w.Open("switch (opcode)");
            for (int opcode = 0; opcode < iface.Events.Count; opcode++)
                EmitDispatchCase(w, iface, iface.Events[opcode], opcode, eventNames[iface.Events[opcode]]);
            w.Close();
            w.Close();
        }
        w.Close();
    }

    static Message? DisposeDestructor(Interface iface)
    {
        var candidates = iface.Requests.Where(r => r.IsDestructor && r.Args.Count == 0).ToList();
        return candidates.FirstOrDefault(r => r.Name == "destroy") ?? candidates.FirstOrDefault();
    }

    static Dictionary<Message, string> MemberNames(Interface iface)
    {
        var requestNames = new HashSet<string>(iface.Requests.Select(r => Names.Pascal(r.Name)));
        return iface.Events.ToDictionary(e => e, e =>
        {
            string name = Names.Pascal(e.Name);
            return requestNames.Contains(name) || ReservedMembers.Contains(name) || name == Names.Pascal(iface.Name) ? name + "Event" : name;
        });
    }

    static void EmitDisposeDestructor(CodeWriter w, Message request, int opcode)
    {
        w.Line($"/// <summary>Sends <c>{request.Name}</c>{(request.Since > 1 ? $" (when bound at version {request.Since} or later)" : "")}, then destroys the proxy.</summary>");
        w.Open("protected override void Destroy()");
        if (request.Since > 1)
        {
            w.Line($"if (BoundVersion < {request.Since})");
            w.Line("    base.Destroy();");
            w.Line("else");
            w.Line($"    Marshal({opcode}, null, {request.Since}, \"{request.Name}\", destroy: true);");
        }
        else
        {
            w.Line($"Marshal({opcode}, null, 1, \"{request.Name}\", destroy: true);");
        }
        w.Close();
    }

    void EmitRequest(CodeWriter w, Interface iface, Message request, int opcode)
    {
        var parameters = new List<string>();
        var body = new List<string>();
        var fixedBlocks = new List<string>();
        string returnType = "void";
        string? newIdType = null;
        bool generic = false;
        int slot = 0;

        foreach (var arg in request.Args)
        {
            string name = Names.Camel(arg.Name);
            string bare = name.TrimStart('@');
            string? enumType = arg.Enum is null ? null : types.EnumType(iface.Name, arg.Enum);
            switch (arg.Type)
            {
                case ArgType.Int:
                    parameters.Add($"{enumType ?? "int"} {name}");
                    body.Add($"args[{slot++}].i = {(enumType is null ? name : $"(int){name}")};");
                    break;
                case ArgType.Uint:
                    parameters.Add($"{enumType ?? "uint"} {name}");
                    body.Add($"args[{slot++}].u = {(enumType is null ? name : $"(uint){name}")};");
                    break;
                case ArgType.Fixed:
                    parameters.Add($"double {name}");
                    body.Add($"args[{slot++}].f = WlFixed.FromDouble({name});");
                    break;
                case ArgType.Fd:
                    parameters.Add($"int {name}");
                    body.Add($"args[{slot++}].h = {name};");
                    break;
                case ArgType.String:
                    parameters.Add($"string{(arg.AllowNull ? "?" : "")} {name}");
                    body.Insert(0, $"using var {bare}Utf8 = new NativeUtf8({name});");
                    body.Add($"args[{slot++}].s = {bare}Utf8.Pointer;");
                    break;
                case ArgType.Array:
                    parameters.Add($"ReadOnlySpan<byte> {name}");
                    fixedBlocks.Add($"fixed (byte* {bare}Data = {name})");
                    body.Add($"var {bare}Array = new WlArray {{ Size = (nuint){name}.Length, Alloc = (nuint){name}.Length, Data = {bare}Data }};");
                    body.Add($"args[{slot++}].a = &{bare}Array;");
                    break;
                case ArgType.Object:
                    string objectType = arg.Interface is null ? "WlProxy" : types.InterfaceType(arg.Interface) ?? "WlProxy";
                    parameters.Add($"{objectType}{(arg.AllowNull ? "?" : "")} {name}");
                    body.Add($"args[{slot++}].o = WlProxy.HandleOf({name});");
                    break;
                case ArgType.NewId when arg.Interface is null:
                    generic = true;
                    returnType = "T";
                    parameters.Add("uint version");
                    body.Add($"args[{slot++}].s = T.NativeInterface->Name;");
                    body.Add($"args[{slot++}].u = version;");
                    body.Add($"args[{slot++}].o = 0;");
                    break;
                case ArgType.NewId:
                    newIdType = types.InterfaceType(arg.Interface!) ?? "WlProxy";
                    returnType = newIdType;
                    body.Add($"args[{slot++}].o = 0;");
                    break;
            }
        }

        string args = slot == 0 ? "null" : "args";
        string call = generic
            ? $"return T.Wrap(MarshalNew({opcode}, {args}, T.NativeInterface, version, {request.Since}, \"{request.Name}\"));"
            : newIdType is not null
                ? $"return {newIdType}.Wrap(MarshalNew({opcode}, {args}, {newIdType}.NativeInterface, BoundVersion, {request.Since}, \"{request.Name}\"));"
                : $"Marshal({opcode}, {args}, {request.Since}, \"{request.Name}\"{(request.IsDestructor ? ", destroy: true" : "")});";

        Docs(w, request.Description, request.Since, request.Args);
        if (generic)
            w.Open($"public T {Names.Pascal(request.Name)}<T>({string.Join(", ", parameters)}) where T : WlProxy, IWaylandProxy<T>");
        else
            w.Open($"public {returnType} {Names.Pascal(request.Name)}({string.Join(", ", parameters)})");
        if (slot > 0)
            w.Line($"WlArgument* args = stackalloc WlArgument[{slot}];");
        foreach (var block in fixedBlocks)
            w.Line(block);
        if (fixedBlocks.Count > 0)
            w.Open("");
        foreach (var line in body)
            w.Line(line);
        w.Line(call);
        if (fixedBlocks.Count > 0)
            w.Close();
        w.Close();
    }

    void EmitDispatchCase(CodeWriter w, Interface iface, Message e, int opcode, string member)
    {
        w.Line($"case {opcode}:");
        w.Indent++;
        int slot = 0;
        var fds = new List<int>();
        foreach (var arg in e.Args)
        {
            if (arg.Type == ArgType.NewId && arg.Interface is not null && types.InterfaceType(arg.Interface) is { } created)
                w.Line($"{created}.Wrap(args[{slot}].o);");
            if (arg.Type == ArgType.Fd)
                fds.Add(slot);
            slot++;
        }
        string invoke = e.Args.Count == 0 ? $"{member}?.Invoke();" : $"{member}?.Invoke(new {EventStructName(iface, e)}(args));";
        if (fds.Count == 0)
            w.Line(invoke);
        else
        {
            // Received fds are closed even if the handler throws.
            w.Line("try");
            w.Line("{");
            w.Indent++;
            w.Line(invoke);
            w.Indent--;
            w.Line("}");
            w.Line("finally");
            w.Line("{");
            w.Indent++;
            foreach (int fd in fds)
                w.Line($"CloseFd(args[{fd}].h);");
            w.Indent--;
            w.Line("}");
        }
        w.Line("break;");
        w.Indent--;
    }

    static string EventStructName(Interface iface, Message e) => Names.Pascal(iface.Name) + Names.Pascal(e.Name) + "Event";

    void EmitEventStruct(CodeWriter w, Interface iface, Message e)
    {
        string name = EventStructName(iface, e);
        w.Line($"/// <summary>Arguments of <see cref=\"{Names.Pascal(iface.Name)}\"/>'s <c>{e.Name}</c> event. Only valid during the event handler.</summary>");
        w.Open($"public readonly unsafe ref struct {name}");
        w.Line("readonly WlArgument* args;");
        w.Line();
        w.Line($"internal {name}(WlArgument* args) => this.args = args;");
        int slot = 0;
        foreach (var arg in e.Args)
        {
            w.Line();
            if (arg.Summary is not null)
                w.Line($"/// <summary>{Escape(arg.Summary)}{(arg.Type == ArgType.Fd ? " Closed by oopshell after the handler returns; dup it to keep it." : "")}</summary>");
            string? enumType = arg.Enum is null ? null : types.EnumType(iface.Name, arg.Enum);
            string prop = Names.Pascal(arg.Name);
            string a = $"args[{slot++}]";
            string nullable = arg.AllowNull ? "?" : "";
            string bang = arg.AllowNull ? "" : "!";
            w.Line(arg.Type switch
            {
                ArgType.Int => $"public {enumType ?? "int"} {prop} => {(enumType is null ? $"{a}.i" : $"({enumType}){a}.i")};",
                ArgType.Uint => $"public {enumType ?? "uint"} {prop} => {(enumType is null ? $"{a}.u" : $"({enumType}){a}.u")};",
                ArgType.Fixed => $"public double {prop} => WlFixed.ToDouble({a}.f);",
                ArgType.Fd => $"public int {prop} => {a}.h;",
                ArgType.String => $"public string{nullable} {prop} => WlProxy.ReadString({a}.s){bang};",
                ArgType.Array => $"public ReadOnlySpan<byte> {prop} => WlProxy.ReadArray({a}.a);",
                _ => ObjectProperty(arg, prop, a, nullable, bang),
            });
        }
        w.Close();
    }

    string ObjectProperty(Arg arg, string prop, string a, string nullable, string bang)
    {
        string type = arg.Interface is null ? "WlProxy" : types.InterfaceType(arg.Interface) ?? "WlProxy";
        if (arg.Type == ArgType.NewId)
            bang = "!";
        return $"public {type}{(arg.Type == ArgType.NewId ? "" : nullable)} {prop} => WlProxy.FromHandle<{type}>({a}.o){bang};";
    }

    static void EmitEnum(CodeWriter w, Interface iface, EnumDef def)
    {
        Docs(w, def.Description);
        if (def.IsBitfield)
            w.Line("[Flags]");
        w.Open($"public enum {Names.Pascal(iface.Name)}{Names.Pascal(def.Name)} : uint");
        foreach (var entry in def.Entries)
        {
            if (entry.Summary is not null)
                w.Line($"/// <summary>{Escape(entry.Summary)}</summary>");
            w.Line($"{Names.Pascal(entry.Name)} = {entry.Value},");
        }
        w.Close();
    }

    static void Docs(CodeWriter w, Description? description, int since = 1, List<Arg>? args = null)
    {
        if (description?.Summary is { } summary)
            w.Line($"/// <summary>{Escape(Capitalize(summary))}</summary>");
        var lines = (description?.Text ?? "").Split('\n').Select(l => l.Trim()).ToList();
        while (lines.Count > 0 && lines[0].Length == 0)
            lines.RemoveAt(0);
        while (lines.Count > 0 && lines[lines.Count - 1].Length == 0)
            lines.RemoveAt(lines.Count - 1);
        if (lines.Count > 0 || since > 1)
        {
            w.Line("/// <remarks>");
            foreach (var line in lines)
                w.Line(line.Length == 0 ? "/// <para/>" : "/// " + Escape(line));
            if (since > 1)
                w.Line($"/// <para>Since version {since}.</para>");
            w.Line("/// </remarks>");
        }
        foreach (var arg in args ?? new List<Arg>())
        {
            if (arg.Summary is not null && arg.Type != ArgType.NewId)
                w.Line($"/// <param name=\"{Names.Camel(arg.Name).TrimStart('@')}\">{Escape(arg.Summary)}</param>");
        }
    }

    static string Capitalize(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);

    static string Escape(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}

/// <summary>Tiny indenting writer. Always uses '\n' so output is identical on every OS.</summary>
public sealed class CodeWriter
{
    readonly StringBuilder sb = new();
    public int Indent;

    public void Raw(string text) => sb.Append(text);

    public void Line(string text = "")
    {
        if (text.Length > 0)
            sb.Append(' ', Indent * 4).Append(text);
        sb.Append('\n');
    }

    public void Open(string header)
    {
        if (header.Length > 0)
            Line(header);
        Line("{");
        Indent++;
    }

    public void Close()
    {
        Indent--;
        Line("}");
    }

    public override string ToString() => sb.ToString();
}
