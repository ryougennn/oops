#!/usr/bin/env python3
"""Generates src/oopshell/Keysym.g.cs from xkbcommon-keysyms.h.

Keeps Latin-1, the function/modifier/dead-key block and the XF86 media keys; any
other keysym is still usable as a raw uint cast to Keysym.
Usage: tools/gen-keysyms.py [/usr/include/xkbcommon/xkbcommon-keysyms.h]
"""
import re, sys

header = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/xkbcommon/xkbcommon-keysyms.h"
keywords = set("abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while".split())

def keep(value):
    return value <= 0xff or 0xfe00 <= value <= 0xffff or 0x1008ff00 <= value <= 0x1008ffff

lines = []
seen = set()
for match in re.finditer(r"^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)", open(header).read(), re.M):
    name, value = match.group(1), int(match.group(2), 16)
    if not keep(value) or name in seen:
        continue
    seen.add(name)
    if name[0].isdigit():
        name = "_" + name
    if name in keywords:
        name = "@" + name
    lines.append(f"    {name} = 0x{value:x},")

out = open("src/oopshell/Keysym.g.cs", "w")
out.write("// <auto-generated> by tools/gen-keysyms.py from xkbcommon-keysyms.h </auto-generated>\n")
out.write("#pragma warning disable CS1591\nnamespace oopshell;\n\n")
out.write("/// <summary>X keysyms (Latin-1, function keys, XF86 media keys). Other keysyms are valid as raw values.</summary>\n")
out.write("public enum Keysym : uint\n{\n")
out.write("\n".join(lines))
out.write("\n}\n")
